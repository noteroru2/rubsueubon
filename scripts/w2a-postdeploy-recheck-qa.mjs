import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const recheck=JSON.parse(fs.readFileSync(path.join(root,'data/seo/w2a-postdeploy-recheck.json'),'utf8'));
const authCsv=fs.readFileSync(path.join(root,'docs/seo/w2b-release-authorization-5r.csv'),'utf8').replace(/^\uFEFF/,'').trim().split(/\r?\n/);
const errors=[]; const assert=(c,m)=>{if(!c)errors.push(m)};
assert(recheck.w2a_source_pages===18,`Expected 18 W2A pages, found ${recheck.w2a_source_pages}`);
assert(recheck.deployment_confirmed===false,'W2A deployment must not be marked confirmed.');
assert(recheck.deployment_state==='SOURCE_NOT_DEPLOYED_TO_PRODUCTION_EVIDENCE',`Unexpected deployment state ${recheck.deployment_state}`);
assert(recheck.gsc_latest_finalized_date==='2026-08-31',`Unexpected GSC date ${recheck.gsc_latest_finalized_date}`);
assert(Number(recheck.post_release_finalized_gsc_days)===0,'Expected 0 finalized GSC days after source release.');
assert(recheck.w2b_selected_rc===12,'Expected 12 selected W2B RCs.');
assert(recheck.w2b_authorized===0,'No W2B RC may be authorized in 5R.');
assert(recheck.w2b_hold===5,'Expected 5 hold candidates.');
assert(recheck.live_evidence?.length>=2,'Need at least two independent live parent fingerprints.');
assert(recheck.live_evidence.every(x=>x.result==='STALE_VS_BATCH5_SOURCE'),'Every sampled live parent must show stale source fingerprint.');
assert(recheck.records?.length===18,'Expected 18 W2A recheck records.');
assert(recheck.records.filter(r=>r.deployment_evidence==='LIVE_PARENT_STALE_SOURCE_FINGERPRINT').length>=5,'Expected >=5 W2A rows covered by sampled stale parent fingerprints.');
const csvText=authCsv.join('\n');
const selected=(csvText.match(/NOT_AUTHORIZED_W2A_NOT_DEPLOYED/g)||[]).length;
assert(selected===12,`Expected 12 not-authorized W2B rows, found ${selected}`);
assert(!csvText.includes('AUTHORIZED_FOR_RELEASE'),'5R authorization overlay must not authorize any W2B candidate.');
if(errors.length){console.error(errors.map(e=>'ERROR: '+e).join('\n'));process.exit(1)}
console.log('W2A source pages: 18');
console.log('Live parent fingerprints sampled: 2 independent parents / 5 W2A children');
console.log('Deployment state: SOURCE_NOT_DEPLOYED_TO_PRODUCTION_EVIDENCE');
console.log('Latest finalized GSC date: 2026-08-31');
console.log('Post-release finalized GSC days: 0');
console.log('W2B selected RCs: 12');
console.log('W2B authorized: 0');
console.log('W2B held: 5');
console.log('Batch 5R QA passed: W2B release remains blocked.');
