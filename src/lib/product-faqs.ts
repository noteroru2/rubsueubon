export function productFaqs(existing: FAQItem[], slug: string, category: string): FAQItem[] {
  const [product, detail] = details[serviceTopic(slug, category)];
  const core = [
    { question: `ขาย${product}ในอุบล ต้องส่งข้อมูลอะไรเพื่อประเมิน?`, answer: `ส่ง${detail} ทาง LINE ${SITE.lineOA} เพื่อประเมินราคาเบื้องต้นจากข้อมูลที่แจ้ง` },
    { question: `ราคา${product}ที่แจ้งทาง LINE เป็นราคาสุดท้ายหรือไม่?`, answer: `เป็นราคาเบื้องต้นครับ รุ่น สเปก สภาพ ประวัติซ่อมและอุปกรณ์มีผลต่อราคา เมื่อนัดตรวจสินค้าจริงจะยืนยันราคาอีกครั้งก่อนตกลงซื้อขายและชำระเงิน` },
    { question: 'อยู่ต่างอำเภอในอุบล นัดรับอย่างไร?', answer: SITE.pickupNote },
    { question: 'ร้านเปิดกี่โมง และประเมินทาง LINE ใช้เวลานานเท่าไร?', answer: `${SITE.storeName} อยู่ที่ ${SITE.addressText} ${SITE.landmark} หน้าร้านเปิด${SITE.storeHoursLabel} ตอบ LINE ${SITE.lineHours} ${SITE.estimateNote}` },
  ];
  const generic = /ร้านอยู่ที่ไหน เปิดกี่โมง|อยู่ต่างอำเภอขายได้ไหม|ราคาที่ประเมินทาง LINE ใช้ได้นาน/;
  const unsuitable = serviceTopic(slug, category) === 'camera' || ['pc', 'audio', 'tv', 'b2b'].includes(serviceTopic(slug, category));
  const seen = new Set(core.map(f => f.question));
  return [...core, ...existing.filter(f => {
    if (seen.has(f.question) || generic.test(f.question) || (unsuitable && /iCloud|MDM/.test(f.question))) return false;
    seen.add(f.question); return true;
  })].slice(0, 10);
}
